import Foundation

@main
struct PiPPolicyTests {
 static func main() {
  var p=PiPPolicy()
  let first=p.begin(now:100)
  precondition(p.step(now:100,active:true,ready:false,possible:true) == .wait)
  precondition(p.step(now:100.5,active:true,ready:true,possible:false) == .wait)
  precondition(p.step(now:101,active:true,ready:true,possible:true) == .start)
  precondition(!p.started)
  precondition(p.step(now:102.9,active:true,ready:true,possible:true) == .wait)
  precondition(p.step(now:103,active:true,ready:true,possible:true) == .retry)
  precondition(p.retries == 1)
  precondition(p.step(now:103.1,active:true,ready:true,possible:true) == .start)
  precondition(p.step(now:105.25,active:true,ready:true,possible:true) == .timeoutDelegate)
  precondition(p.step(now:105.5,active:true,ready:true,possible:true) == .cancelled)
  let second=p.begin(now:200)
  precondition(first != second)
  precondition(p.step(now:206,active:true,ready:false,possible:false) == .timeoutReadiness)
  _=p.begin(now:300)
  precondition(p.step(now:300,active:true,ready:true,possible:true) == .start)
  p.cancel()
  precondition(p.step(now:303,active:true,ready:true,possible:true) == .cancelled)
  _=p.begin(now:400)
  precondition(p.step(now:400,active:true,ready:true,possible:true) == .start)
  precondition(p.step(now:401,active:false,ready:true,possible:true) == .wait)
  precondition(!p.retryValid && p.acceptDidStart)
  precondition(p.didStart() == .accepted)
  precondition(p.retries == 0)
  _=p.begin(now:450)
  precondition(p.step(now:450,active:false,ready:true,possible:true) == .cancelled)
  precondition(p.didStart() == .rejected) // Never issued start in background.
  precondition(p.step(now:451,active:true,ready:true,possible:true) == .cancelled)
  _=p.begin(now:500)
  precondition(p.step(now:500,active:true,ready:true,possible:true) == .start)
  p.willStart(now:501)
  precondition(p.step(now:502,active:true,ready:true,possible:true) == .wait)
  precondition(p.step(now:506.9,active:false,ready:true,possible:true) == .wait)
  precondition(p.step(now:507,active:false,ready:true,possible:true) == .timeoutDidStart)
  precondition(p.timedOut && p.acceptDidStart && !p.retryValid)
  precondition(p.step(now:508,active:true,ready:true,possible:true) == .cancelled)
  precondition(p.didStart() == .late)
  precondition(p.retries == 0)
  _=p.begin(now:550)
  precondition(p.step(now:550,active:true,ready:true,possible:true) == .start)
  p.background()
  precondition(p.step(now:552,active:false,ready:true,possible:true) == .timeoutDelegate)
  precondition(p.timedOut && p.acceptDidStart && p.retries == 0)
  precondition(p.didStart() == .late)
  _=p.begin(now:570)
  precondition(p.step(now:570,active:true,ready:true,possible:true) == .start)
  p.cancel()
  precondition(!p.timedOut && !p.acceptDidStart)
  precondition(p.didStart() == .rejected)
  let previous=p.token
  let replacement=p.begin(now:580)
  precondition(previous != replacement && !p.acceptDidStart)
  precondition(p.didStart() == .rejected)
  _=p.begin(now:600)
  precondition(p.step(now:600,active:true,ready:true,possible:true) == .start)
  precondition(p.didStart() == .accepted)
  precondition(p.started && !p.valid)
  precondition(p.step(now:603,active:true,ready:true,possible:true) == .cancelled)
  var r=PiPRenderPolicy()
  let a=r.nextTick(hostSeconds:1000)
  let b=r.nextTick(hostSeconds:1000)
  let c=r.nextTick(hostSeconds:999)
  precondition(a < b && b < c)
  precondition(r.failed(active:false) == .flush)
  precondition(r.failed(active:false) == .rebuild)
  r.rebuilt()
  precondition(r.nextTick(hostSeconds:1000.2) > c)
  precondition(r.failed(active:true) == .flush)
  precondition(r.failed(active:true) == .deferRebuild)
  r.rebuilt()
  precondition(r.failures == 0)
  precondition(r.nextTick(hostSeconds:1001) > c)
  print("PiPPolicyTests PASS (actual Swift policy execution; not AVKit/device validation)")
 }
}
